// Precomputes which points of a Fibonacci sphere fall on land, using Natural Earth
// land polygons (public domain, via world-atlas). Writes public/globe-land.js, a
// base64 bitmask the globe decodes at runtime. Run with: npm run build:land
import { readFile, writeFile } from "node:fs/promises";
import { feature } from "topojson-client";

const POINT_COUNT = 42000;

const topo = JSON.parse(await readFile(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url), "utf8"));
const land = feature(topo, topo.objects.land);

const polygons = [];
for (const f of land.features) {
  const g = f.geometry;
  const parts = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const rings of parts) {
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (const [x, y] of rings[0]) {
      minX = Math.min(minX, x); maxX = Math.max(maxX, x);
      minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
    polygons.push({ rings, minX, minY, maxX, maxY });
  }
}

function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function isLand(lat, lon) {
  for (const p of polygons) {
    if (lon < p.minX || lon > p.maxX || lat < p.minY || lat > p.maxY) continue;
    if (inRing(lon, lat, p.rings[0]) && !p.rings.slice(1).some((hole) => inRing(lon, lat, hole))) return true;
  }
  return false;
}

const bits = new Uint8Array(Math.ceil(POINT_COUNT / 8));
const golden = Math.PI * (3 - Math.sqrt(5));
let landCount = 0;
for (let i = 0; i < POINT_COUNT; i++) {
  const y = 1 - (i / (POINT_COUNT - 1)) * 2;
  const r = Math.sqrt(1 - y * y);
  const theta = i * golden;
  const lat = Math.asin(y) * (180 / Math.PI);
  const lon = Math.atan2(Math.sin(theta) * r, Math.cos(theta) * r) * (180 / Math.PI);
  if (isLand(lat, lon)) {
    bits[i >> 3] |= 1 << (i & 7);
    landCount++;
  }
}

const out = `// Generated by scripts/build-land-mask.mjs from Natural Earth land polygons. Do not edit.
export const POINT_COUNT = ${POINT_COUNT};
export const LAND_MASK = "${Buffer.from(bits).toString("base64")}";
`;
await writeFile(new URL("../public/globe-land.js", import.meta.url), out);
console.log(`land points: ${landCount} / ${POINT_COUNT} (${((landCount / POINT_COUNT) * 100).toFixed(1)}%)`);
